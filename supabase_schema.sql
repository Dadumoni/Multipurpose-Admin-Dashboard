-- Backup Table in Supabase: public.post
-- Single table containing video title, video link, and thumbnail link:
CREATE TABLE IF NOT EXISTS public.post (
  id bigint generated by default as identity primary key,
  title text not null,
  video_url text not null unique,
  thumbnail_url text null,
  created_at timestamp with time zone default now()
);

-- Index on video_url (unique) and created_at
CREATE INDEX IF NOT EXISTS idx_post_created_at_desc ON public.post (created_at DESC);

-- Grants
GRANT ALL ON TABLE public.post TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;
